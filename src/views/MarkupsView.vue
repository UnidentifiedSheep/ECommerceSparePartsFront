<script setup lang="ts">
import { useDialogGuard } from '@/composables/useDialogGuard'
import { useConfirmedDelete } from '@/composables/useConfirmedDelete'
import { computed, onMounted, onScopeDispose, reactive, ref, watch } from 'vue'
import { ElMessage } from 'element-plus'
import { Delete, Edit } from '@element-plus/icons-vue'
import ActionIconButton from '@/components/common/ActionIconButton.vue'
import PageHeader from '@/components/common/PageHeader.vue'
import ZeroPagination from '@/components/common/ZeroPagination.vue'
import DataLoadError from '@/components/common/DataLoadError.vue'
import { classifyDataLoadError, type DataLoadErrorKind } from '@/utils/dataLoadError'
import type { CurrencyModel } from '@/models/currencyModel.ts'
import { getCurrencies } from '@/services/api/currencies.ts'
import {
  getMarkupGroups,
  getMarkupGroupRanges,
  getAllMarkupGroupRanges,
  upsertMarkupGroup,
  deleteMarkupGroup,
  type MarkupGroupModel,
  type MarkupRangeModel,
} from '@/services/api/markups.ts'
import { useI18n } from '@/i18n'
import { usePermissions } from '@/composables/usePermissions'
import { resolveDefaultCurrencyId } from '@/utils/defaultCurrency.ts'

interface RangeFormRow {
  key: string
  rangeStart: number
  rangeEnd: number
  markupPercent: number
}

const { locale, t } = useI18n()
const { hasPermission } = usePermissions()
const canEditMarkups = computed(() => hasPermission('MARKUP_CREATE'))
const canDeleteMarkups = computed(() => hasPermission('MARKUP_DELETE'))
const deletion = useConfirmedDelete()
const deletingGroupId = ref<number | null>(null)

const groups = ref<MarkupGroupModel[]>([])
const currencies = ref<CurrencyModel[]>([])
const isLoading = ref(false)
const isSaving = ref(false)
const isLoadingCurrencies = ref(false)
const drawerOpen = ref(false)
const editingGroupId = ref<number | null>(null)
const selectedGroupId = ref<number | null>(null)
const page = ref(0)
const limit = ref(20)
const hasNext = ref(false)
const groupsError = ref<DataLoadErrorKind | null>(null)
const rangesError = ref<DataLoadErrorKind | null>(null)
const selectedGroupRanges = ref<MarkupRangeModel[]>([])
const rangesPage = ref(0)
const rangesSize = ref(20)
const rangesHasNext = ref(false)
const isLoadingRanges = ref(false)
const preparingEditId = ref<number | null>(null)
let groupsRequestId = 0
let rangesRequestId = 0
let disposed = false
onScopeDispose(() => { disposed = true; groupsRequestId++; rangesRequestId++ })

const form = reactive<{
  name: string
  currencyId: number | null
  ranges: RangeFormRow[]
}>({
  name: '',
  currencyId: null,
  ranges: [],
})

const drawerTitle = computed(() => editingGroupId.value
  ? t('markups.edit')
  : t('markups.create'))

const currencyById = computed(() => new Map(currencies.value.map((currency) => [currency.id, currency])))
const selectedGroup = computed(() => groups.value.find((group) => group.id === selectedGroupId.value))
watch(selectedGroupId, () => { rangesPage.value = 0 })
watch(rangesSize, () => { rangesPage.value = 0 })
watch([selectedGroup, rangesPage, rangesSize], () => void loadRanges())

watch([page, limit], () => {
  loadGroups()
})

onMounted(async () => {
  await Promise.all([
    loadCurrencies(),
    loadGroups(),
  ])
})

async function loadCurrencies() {
  isLoadingCurrencies.value = true
  try {
    const response = await getCurrencies()
    currencies.value = response.currencies
  } catch (error) {
    ElMessage.error(error instanceof Error ? error.message : t('markups.loadCurrenciesError'))
  } finally {
    isLoadingCurrencies.value = false
  }
}

async function loadGroups() {
  const requestId = ++groupsRequestId
  isLoading.value = true
  groupsError.value = null
  try {
    const response = await getMarkupGroups({
      page: page.value,
      size: limit.value,
    })
    if (requestId !== groupsRequestId) return
    groups.value = response.groups
    hasNext.value = response.groups.length === limit.value
    ensureSelectedGroup()
  } catch (error) {
    if (requestId === groupsRequestId) groupsError.value = classifyDataLoadError(error)
  } finally {
    if (requestId === groupsRequestId) isLoading.value = false
  }
}

async function loadRanges() {
  const requestId = ++rangesRequestId
  selectedGroupRanges.value = []
  rangesError.value = null
  rangesHasNext.value = false
  isLoadingRanges.value = Boolean(selectedGroup.value)
  if (!selectedGroup.value) return
  try {
    const ranges = await getMarkupGroupRanges(selectedGroup.value.id, rangesPage.value, rangesSize.value)
    if (requestId !== rangesRequestId) return
    selectedGroupRanges.value = ranges
    rangesHasNext.value = ranges.length === rangesSize.value
  } catch (error) {
    if (requestId === rangesRequestId) rangesError.value = classifyDataLoadError(error)
  } finally {
    if (requestId === rangesRequestId) isLoadingRanges.value = false
  }
}

function openCreateDrawer() {
  if (deletingGroupId.value !== null) return
  if (!canEditMarkups.value) return
  editingGroupId.value = null
  form.name = ''
  form.currencyId = resolveDefaultCurrencyId(currencies.value) ?? null
  form.ranges = [createRangeRow()]
  drawerOpen.value = true
}

async function removeGroup(group: MarkupGroupModel) {
  if (!canDeleteMarkups.value || deletingGroupId.value !== null || preparingEditId.value !== null || isLoading.value) return
  deletingGroupId.value = group.id
  try {
    await deletion.remove(String(group.id), group.name || `${t('markups.unnamed')} #${group.id}`, async () => {
      if (!canDeleteMarkups.value || disposed) return
      await deleteMarkupGroup(group.id)
      if (disposed) return
      groupsRequestId++
      groups.value = groups.value.filter(item => item.id !== group.id)
      ensureSelectedGroup()
      ElMessage.success(t('markups.deleted'))
      if (groups.value.length === 0 && page.value > 0) page.value--
      else await loadGroups()
    })
  } catch (error) {
    if (!disposed) ElMessage.error(error instanceof Error ? error.message : t('markups.deleteError'))
  } finally {
    deletingGroupId.value = null
  }
}

async function openEditDrawer(group: MarkupGroupModel) {
  if (!canEditMarkups.value || preparingEditId.value !== null || deletingGroupId.value !== null) return
  preparingEditId.value = group.id
  let ranges: MarkupRangeModel[]
  try {
    ranges = await getAllMarkupGroupRanges(group.id)
    if (disposed) return
  } catch (error) {
    if (!disposed) ElMessage.error(error instanceof Error ? error.message : t('markups.loadError'))
    return
  } finally {
    preparingEditId.value = null
  }
  editingGroupId.value = group.id
  form.name = group.name ?? ''
  form.currencyId = group.currencyId
  form.ranges = sortedRanges(ranges).map((range) => ({
    key: crypto.randomUUID(),
    rangeStart: range.rangeStart,
    rangeEnd: range.rangeEnd,
    markupPercent: range.markup * 100,
  }))
  if (form.ranges.length === 0) {
    form.ranges = [createRangeRow()]
  }
  drawerOpen.value = true
}

function addRange() {
  const last = form.ranges[form.ranges.length - 1]
  form.ranges.push(createRangeRow(last?.rangeEnd ?? 0))
}

function removeRange(index: number) {
  if (form.ranges.length === 1) return
  form.ranges.splice(index, 1)
}

function createRangeRow(start = 0): RangeFormRow {
  return {
    key: crypto.randomUUID(),
    rangeStart: start,
    rangeEnd: start + 1,
    markupPercent: 0,
  }
}

async function saveGroup() {
  if (!canEditMarkups.value || isSaving.value) return
  const validationError = validateForm()
  if (validationError) {
    ElMessage.warning(validationError)
    return
  }

  isSaving.value = true
  try {
    const saved = await upsertMarkupGroup({
      id: editingGroupId.value ?? undefined,
      name: form.name.trim() || null,
      currencyId: form.currencyId!,
      ranges: form.ranges.map((range) => ({
        rangeStart: range.rangeStart,
        rangeEnd: range.rangeEnd,
        markup: range.markupPercent / 100,
      })),
    })
    ElMessage.success(t('markups.saved'))
    drawerOpen.value = false
    selectedGroupId.value = saved.id
    await loadGroups()
  } catch (error) {
    ElMessage.error(error instanceof Error ? error.message : t('markups.saveError'))
  } finally {
    isSaving.value = false
  }
}

function selectGroup(group?: MarkupGroupModel) {
  if (group) selectedGroupId.value = group.id
}

function ensureSelectedGroup() {
  if (groups.value.length === 0) {
    selectedGroupId.value = null
    return
  }

  if (!selectedGroupId.value || !groups.value.some((group) => group.id === selectedGroupId.value)) {
    selectedGroupId.value = groups.value[0]?.id ?? null
  }
}

function markupRowClassName({ row }: { row: MarkupGroupModel }) {
  return row.id === selectedGroupId.value ? 'markup-row markup-row--selected' : 'markup-row'
}

function validateForm() {
  if (!form.currencyId) return t('markups.currencyRequired')
  if (form.ranges.length === 0) return t('markups.rangesRequired')

  const invalidRangeIndex = form.ranges.findIndex((range) => range.rangeEnd <= range.rangeStart)
  if (invalidRangeIndex >= 0) {
    return t('markups.rangeInvalid', { index: invalidRangeIndex + 1 })
  }

  return ''
}

function sortedRanges(ranges: MarkupRangeModel[]) {
  return [...ranges].sort((a, b) => a.rangeStart - b.rangeStart)
}

function currencyLabel(currencyId: number) {
  const currency = currencyById.value.get(currencyId)
  if (!currency) return `#${currencyId}`
  return `${currency.name} (${currency.currencySign})`
}

function formatMoney(value: number, currencyId: number) {
  const currency = currencyById.value.get(currencyId)
  const amount = new Intl.NumberFormat(locale.value, {
    maximumFractionDigits: 2,
  }).format(value)
  return currency ? `${amount} ${currency.currencySign}` : amount
}

function formatPercent(value: number) {
  return new Intl.NumberFormat(locale.value, {
    style: 'percent',
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(value)
}
const draftGuard = useDialogGuard(drawerOpen, isSaving, () => form)
</script>

